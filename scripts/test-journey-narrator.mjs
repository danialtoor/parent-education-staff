import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFileSync} from 'node:fs';
const js=ts.transpileModule(readFileSync(new URL('../lib/journey-narrator.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ES2020}}).outputText;
const {DeviceNarrator}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
let current,cancelled=0,paused=0,resumed=0,finished=0,errors=0;
const voice={voiceURI:'spanish',lang:'es-MX'};
const engine={getVoices:()=>[voice],speak:u=>{current=u},cancel:()=>cancelled++,pause:()=>paused++,resume:()=>resumed++};
const narrator=new DeviceNarrator(engine,text=>({text}));
const request={text:'Hola',language:'es-MX',voiceURI:'spanish',rate:.85,onStart:()=>{},onEnd:()=>finished++,onError:()=>errors++};
narrator.speak(request);assert.equal(current.voice,voice);assert.equal(current.rate,.85);
current.onstart();const staleEnd=current.onend;
narrator.pause();narrator.resume();assert.equal(paused,1);assert.ok(resumed>=2);
narrator.speak({...request,text:'Siguiente'});assert.equal(cancelled,1);staleEnd();assert.equal(finished,0);
current.onstart();current.onend();assert.equal(finished,1);
narrator.speak(request);current.onerror({error:'not-allowed'});assert.equal(errors,1);
narrator.speak(request);const endAfterUnmount=current.onend;narrator.stop();endAfterUnmount();assert.equal(finished,1);
console.log('Narration checks passed: voice selection, speed, pause/resume, stale callbacks, errors, cleanup.');
